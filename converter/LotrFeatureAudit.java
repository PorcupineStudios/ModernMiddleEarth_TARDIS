import java.nio.file.*;
import java.util.*;
import java.util.regex.*;
import java.util.stream.*;
import java.util.zip.*;

/**
 * Feature audit of LOTR 1.7.10 (Update 36.15) against the port: every class in LOTR's jar is given a feature by
 * docs/plans/lotr-feature-audit/rules.tsv (first matching regex wins; inner classes count with their outer class),
 * each feature has a status in features.tsv, and the port is checked for counterparts where that can be automatic:
 * <ul>
 * <li>block and item classes: how many of LOTR's ids made by that class (converter/export blocks.json, items.json,
 * nearest LOTR class) converter/idtable.json maps to a port id</li>
 * <li>NPC and animal classes: an NPC type or mount breed of the same name in the port's data</li>
 * <li>structure classes: exported by the converter, placed as a port structure, and whether LOTR's biome decorators
 * placed it (export world.json)</li>
 * <li>biome classes: a port biome of the same name</li>
 * <li>mentions: port and converter files (java, py, md) that name the class</li>
 * </ul>
 * Writes classes.tsv (one row per LOTR class) and the generated part of docs/plans/lotr-feature-audit.md, and fails
 * if a class has no feature or a feature has no status. Run from the repo root, JDK 21, after a converter export:
 *
 *   java converter/LotrFeatureAudit.java "path/to/LOTRMod v36.15.jar"
 */
public class LotrFeatureAudit {
    static final Path DIR = Path.of("docs/plans/lotr-feature-audit");
    static final Path DOC = Path.of("docs/plans/lotr-feature-audit.md");
    static final Path EXPORT = Path.of("converter/export");
    static final Path GEN = Path.of("lotr/src/generated/resources/data/lotr_port");
    static final Path MAIN = Path.of("lotr/src/main/resources/data/lotr_port");
    static final String BEGIN = "<!-- generated by converter/LotrFeatureAudit.java: begin -->";
    static final String END = "<!-- generated by converter/LotrFeatureAudit.java: end -->";

    record Feature(String id, String category, String status, String title, String evidence) {}

    public static void main(String[] args) throws Exception {
        // LOTR's classes, inner classes folded into their outer class
        SortedSet<String> classes = new TreeSet<>();
        try (ZipFile zip = new ZipFile(args[0])) {
            zip.stream().map(ZipEntry::getName).filter(n -> n.endsWith(".class"))
                    .map(n -> n.substring(0, n.length() - 6).replaceAll("\\$.*", "").replaceFirst("^lotr/", ""))
                    .forEach(classes::add);
        }
        List<String[]> rules = tsv(DIR.resolve("rules.tsv"));
        Map<String, Feature> features = new LinkedHashMap<>();
        for (String[] r : tsv(DIR.resolve("features.tsv"))) features.put(r[0], new Feature(r[0], r[1], r[2], r[3], r[4]));

        Map<String, int[]> ids = idCoverage();
        Set<String> npcTypes = names(GEN.resolve("npc"), MAIN.resolve("npc"), GEN.resolve("mount"));
        Matcher em = Pattern.compile("\"name\": \"lotr\\.(\\w+)\",\\s*\"id\": \\d+,\\s*\"class\": \"[\\w.]+\\.(LOTREntity\\w+)\"")
                .matcher(Files.readString(EXPORT.resolve("npcs.json")));
        while (em.find()) REGISTERED.put(em.group(2), snake(em.group(1)));
        String world = Files.readString(EXPORT.resolve("world.json"));
        Matcher bm = Pattern.compile("\"class\": \"lotr\\.common\\.world\\.biome\\.(LOTRBiomeGen\\w+)\",\\s*\"fields\": \\{[^{}]*?\"biomeName\": \"(\\w+)\"").matcher(world);
        while (bm.find()) BIOMES.computeIfAbsent(bm.group(1), k -> new ArrayList<>()).add(snake(bm.group(2)));
        Set<String> structures = dirs(GEN.resolve("structure"));
        Set<String> biomes = names(GEN.resolve("worldgen/biome"));
        String structureExport = gz(EXPORT.resolve("structures.json.gz"));
        Set<String> exported = matches(structureExport, "\"(LOTR(?:WorldGen|VillageGen)\\w+)\":\\[");
        Set<String> decorated = matches(Files.readString(EXPORT.resolve("world.json")), "(LOTR(?:WorldGen|VillageGen)\\w+)");
        Map<String, Set<String>> mentions = mentions();

        List<String> rows = new ArrayList<>(), unmapped = new ArrayList<>();
        Map<String, List<String>> byFeature = new LinkedHashMap<>();
        Map<String, List<String>> gaps = new TreeMap<>();
        for (String c : classes) {
            String f = null;
            for (String[] r : rules) if (c.matches(r[0])) { f = r[1]; break; }
            if (f == null || !features.containsKey(f)) { unmapped.add(c + (f == null ? "" : " -> " + f)); continue; }
            String simple = c.substring(c.lastIndexOf('/') + 1);
            String auto = auto(c, simple, ids, npcTypes, structures, biomes, exported, decorated);
            if (auto.startsWith("MISSING")) gaps.computeIfAbsent(f, k -> new ArrayList<>()).add(simple + " (" + auto.substring(8) + ")");
            Set<String> m = mentions.getOrDefault(simple, Set.of());
            rows.add(String.join("\t", c, f, auto, m.size() + "", String.join(" ", m.stream().limit(3).toList())));
            byFeature.computeIfAbsent(f, k -> new ArrayList<>()).add(c);
        }
        if (!unmapped.isEmpty()) {
            unmapped.forEach(u -> System.err.println("no feature: " + u));
            System.exit(1);
        }
        Files.writeString(DIR.resolve("classes.tsv"), Stream.concat(Stream.of("class\tfeature\tport counterpart (automatic)\tmentions\tmentioned in"),
                rows.stream()).collect(Collectors.joining("\n", "", "\n")));

        // the generated part of the report
        StringBuilder out = new StringBuilder(BEGIN + "\n\n");
        List<String> statuses = List.of("Ported", "Replaced", "Partial", "Not ported", "Dropped");
        Map<String, Map<String, int[]>> totals = new LinkedHashMap<>(); // category -> status -> {features, classes}
        for (Feature f : features.values()) {
            int n = byFeature.getOrDefault(f.id, List.of()).size();
            if (n == 0) { System.err.println("feature without classes: " + f.id); System.exit(1); }
            if (!statuses.contains(f.status)) { System.err.println("bad status: " + f.id + " " + f.status); System.exit(1); }
            int[] t = totals.computeIfAbsent(f.category, k -> new LinkedHashMap<>()).computeIfAbsent(f.status, k -> new int[2]);
            t[0]++; t[1] += n;
        }
        out.append("### Totals (features / LOTR classes)\n\n| Category | ")
                .append(String.join(" | ", statuses)).append(" | All |\n|---|").append("---|".repeat(statuses.size() + 1)).append("\n");
        int[][] grand = new int[statuses.size() + 1][2];
        for (var e : totals.entrySet()) {
            out.append("| ").append(e.getKey());
            int[] all = new int[2];
            for (int i = 0; i < statuses.size(); i++) {
                int[] t = e.getValue().getOrDefault(statuses.get(i), new int[2]);
                out.append(" | ").append(t[0] == 0 ? "" : t[0] + " / " + t[1]);
                all[0] += t[0]; all[1] += t[1]; grand[i][0] += t[0]; grand[i][1] += t[1];
            }
            grand[statuses.size()][0] += all[0]; grand[statuses.size()][1] += all[1];
            out.append(" | ").append(all[0]).append(" / ").append(all[1]).append(" |\n");
        }
        out.append("| **All**");
        for (int[] g : grand) out.append(" | **").append(g[0]).append(" / ").append(g[1]).append("**");
        out.append(" |\n\nEvery one of LOTR's ").append(classes.size())
                .append(" top-level classes (inner classes counted with their outer class) is in exactly one feature; the full list is `lotr-feature-audit/classes.tsv`.\n");

        String category = null;
        for (Feature f : features.values()) {
            if (!f.category.equals(category)) {
                category = f.category;
                out.append("\n### ").append(category).append("\n\n| Feature | Status | LOTR classes | Port counterpart, or what is missing |\n|---|---|---|---|\n");
            }
            List<String> cs = byFeature.get(f.id);
            String autoSummary = summary(cs, rows);
            out.append("| ").append(f.title).append(" `").append(f.id).append("` | ").append(f.status).append(" | ")
                    .append(cs.size()).append(autoSummary.isEmpty() ? "" : " (" + autoSummary + ")").append(" | ")
                    .append(f.evidence).append(" |\n");
        }
        out.append("\n### Automatic gaps\n\nClasses inside a feature whose port counterpart the automatic check did not find (an NPC type, biome or "
                + "structure of that name; block or item ids not mapped). Some are covered under another name or by design; the feature row says which.\n\n");
        for (var e : gaps.entrySet()) out.append("- `").append(e.getKey()).append("`: ").append(String.join(", ", e.getValue())).append("\n");
        out.append("\n").append(END);

        String doc = Files.readString(DOC);
        int a = doc.indexOf(BEGIN), b = doc.indexOf(END);
        Files.writeString(DOC, doc.substring(0, a) + out + doc.substring(b + END.length()));
        System.out.println(classes.size() + " classes, " + features.size() + " features, " + gaps.values().stream().mapToInt(List::size).sum() + " automatic gaps");
    }

    /** "ids 3/4", "npc type", "MISSING npc type"... for one class; MISSING marks what the port lacks. */
    static String auto(String c, String simple, Map<String, int[]> ids, Set<String> npcTypes, Set<String> structures,
                       Set<String> biomes, Set<String> exported, Set<String> decorated) {
        int[] id = ids.get(c.replace('/', '.'));
        if (id != null) return id[1] == id[0] ? "ids " + id[1] + "/" + id[0] : "MISSING ids " + id[1] + "/" + id[0] + " mapped";
        if (c.matches("common/entity/(npc|animal)/LOTREntity\\w+")) {
            String n = REGISTERED.get(simple); // LOTR's entity name, which the converter's NPC ids follow
            if (n == null) return "not registered in LOTR (base or unused class)";
            String own = snake(simple.substring(10));
            if (npcTypes.contains(n) || npcTypes.contains(own)) return "npc " + (npcTypes.contains(n) ? n : own);
            return "MISSING npc type " + n;
        }
        if (c.matches("common/world/biome/LOTRBiomeGen\\w+")) {
            // a class can make several of LOTR's biomes (export world.json); each is a port biome of its name
            List<String> made = BIOMES.get(simple);
            if (made == null) return "makes no LOTR biome itself (base class)";
            List<String> missing = made.stream().filter(b -> !biomes.contains(b)).toList();
            return missing.isEmpty() ? "biome " + String.join(" ", made) : "MISSING biome " + String.join(" ", missing);
        }
        if (c.matches("common/world/(structure2?|village)/LOTR(WorldGen|VillageGen)\\w+")) {
            boolean village = simple.startsWith("LOTRVillageGen");
            String n = village ? "village_" + snake(simple.substring(14)) : snake(simple.substring(12));
            if (structures.contains(n)) return "structure " + n;
            if (!exported.contains(simple)) return decorated.contains(simple) ? "MISSING not exported, LOTR placed it" : "not exported";
            return decorated.contains(simple) ? "MISSING exported, LOTR placed it, not placed" : "exported (piece of a village or larger build)";
        }
        return "";
    }

    /** Entity class -> its registered LOTR name, snake-cased (export npcs.json "entities"). */
    static final Map<String, String> REGISTERED = new HashMap<>();
    /** Biome class -> the LOTR biomes it makes, snake-cased (export world.json). */
    static final Map<String, List<String>> BIOMES = new HashMap<>();

    /** Short summary of a feature's automatic results. */
    static String summary(List<String> cs, List<String> rows) {
        Map<String, String> auto = rows.stream().map(r -> r.split("\t", -1)).collect(Collectors.toMap(r -> r[0], r -> r[2]));
        int have = 0, miss = 0, idsHave = 0, idsAll = 0;
        for (String c : cs) {
            String a = auto.get(c);
            Matcher m = Pattern.compile("ids (\\d+)/(\\d+)").matcher(a);
            if (m.find()) {
                // "ids 3/4" is mapped/all, "MISSING ids 1/4 mapped" too
                idsHave += Integer.parseInt(m.group(1)); idsAll += Integer.parseInt(m.group(2));
            } else if (a.startsWith("MISSING")) miss++;
            else if (a.matches("(npc|biome|structure) .*")) have++;
        }
        List<String> parts = new ArrayList<>();
        if (idsAll > 0) parts.add(idsHave + "/" + idsAll + " ids mapped");
        if (have + miss > 0) parts.add(have + "/" + (have + miss) + " found by name");
        return String.join(", ", parts);
    }

    /** LOTR class (nearest in each id's class chain, and every superclass up to LOTR's own) -> {ids, ids mapped}. */
    static Map<String, int[]> idCoverage() throws Exception {
        String table = Files.readString(Path.of("converter/idtable.json"));
        Set<String> mapped = matches(table, "\"(lotr:[^\"#]+)#");
        Map<String, int[]> out = new HashMap<>();
        for (String f : List.of("blocks.json", "items.json")) {
            String json = Files.readString(EXPORT.resolve(f));
            Matcher m = Pattern.compile("\"id\": \"(lotr:[^\"]+)\",\\s*\"classes\": \\[([^\\]]*)\\]").matcher(json);
            while (m.find()) {
                boolean ok = mapped.contains(m.group(1));
                for (String cls : matches(m.group(2), "\"(lotr\\.[\\w.]+)\"")) {
                    int[] t = out.computeIfAbsent(cls.substring(5), k -> new int[2]);
                    t[0]++; if (ok) t[1]++;
                }
            }
        }
        return out;
    }

    /** Simple class name (LOTRxxx) -> files of the port and converter that name it. */
    static Map<String, Set<String>> mentions() throws Exception {
        Map<String, Set<String>> out = new HashMap<>();
        Pattern p = Pattern.compile("\\bLOTR[A-Z]\\w*");
        for (String root : List.of("lotr/src/main/java", "lotr/src/test", "lotr/docs", "converter", "lotr/CLAUDE.md")) {
            try (Stream<Path> s = Files.walk(Path.of(root))) {
                for (Path f : s.filter(x -> x.toString().matches(".*\\.(java|py|md)") && !x.toString().contains("LotrFeatureAudit")
                        && !x.toString().matches(".*[\\\\/](build|cache|export|run)[\\\\/].*")).toList()) {
                    Matcher m = p.matcher(Files.readString(f));
                    while (m.find()) out.computeIfAbsent(m.group(), k -> new TreeSet<>()).add(f.getFileName().toString());
                }
            }
        }
        return out;
    }

    static List<String[]> tsv(Path p) throws Exception {
        return Files.readAllLines(p).stream().filter(l -> !l.isBlank() && !l.startsWith("#")).map(l -> l.split("\t", -1)).toList();
    }

    static Set<String> names(Path... dirs) throws Exception {
        Set<String> out = new HashSet<>();
        for (Path d : dirs) if (Files.isDirectory(d)) try (Stream<Path> s = Files.walk(d)) {
            s.map(x -> x.getFileName().toString()).filter(n -> n.endsWith(".json")).forEach(n -> out.add(n.substring(0, n.length() - 5)));
        }
        return out;
    }

    static Set<String> dirs(Path d) throws Exception {
        try (Stream<Path> s = Files.list(d)) { return s.map(x -> x.getFileName().toString()).collect(Collectors.toSet()); }
    }

    static String gz(Path p) throws Exception {
        try (var in = new GZIPInputStream(Files.newInputStream(p))) { return new String(in.readAllBytes()); }
    }

    static Set<String> matches(String s, String regex) {
        Set<String> out = new LinkedHashSet<>();
        Matcher m = Pattern.compile(regex).matcher(s);
        while (m.find()) out.add(m.group(1));
        return out;
    }

    static String snake(String s) {
        return s.replaceAll("([a-z0-9])([A-Z])", "$1_$2").replaceAll("([A-Z])([A-Z][a-z])", "$1_$2").toLowerCase();
    }
}
