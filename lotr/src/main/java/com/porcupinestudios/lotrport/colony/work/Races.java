package com.porcupinestudios.lotrport.colony.work;

import com.mojang.serialization.Codec;
import com.mojang.serialization.codecs.RecordCodecBuilder;
import com.porcupinestudios.ringbearer.api.data.CodecJsonLoader;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import net.minecraft.resources.ResourceLocation;
import net.neoforged.neoforge.common.NeoForge;
import net.neoforged.neoforge.event.AddReloadListenerEvent;

/**
 * Races for colony work (RingRealms' races: hobbit, dwarf, elf, orc, goblin, half-troll, man):
 * {@code data/<ns>/colony_race/<race>.json} {@code {"types": [npc types]}}, generated by {@code converter/colonies.py};
 * a type in no list is a man. Job proficiency is per race ({@code colony_job} {@code races}).
 */
public final class Races {
    public static final String MAN = "man";

    record Def(List<ResourceLocation> types) {
        static final Codec<Def> CODEC = RecordCodecBuilder.create(i -> i.group(
                ResourceLocation.CODEC.listOf().optionalFieldOf("types", List.of()).forGetter(Def::types))
                .apply(i, Def::new));
    }

    private static final CodecJsonLoader<Def> LOADER = new CodecJsonLoader<>("colony_race", Def.CODEC);
    private static Map<ResourceLocation, Def> indexedFrom;
    private static Map<ResourceLocation, String> index = Map.of();

    private Races() {}

    public static void register() {
        NeoForge.EVENT_BUS.addListener((AddReloadListenerEvent e) -> e.addListener(LOADER));
    }

    /** The race of an NPC type. */
    public static synchronized String of(ResourceLocation type) {
        Map<ResourceLocation, Def> now = LOADER.entries();
        if (now != indexedFrom) {
            Map<ResourceLocation, String> m = new HashMap<>();
            now.forEach((race, def) -> def.types().forEach(t -> m.put(t, race.getPath())));
            index = m;
            indexedFrom = now;
        }
        return index.getOrDefault(type, MAN);
    }

    public static List<String> loadProblems() {
        return LOADER.lastErrors();
    }
}
