package com.porcupinestudios.lotrport.client;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.porcupinestudios.lotrport.content.ContentData;
import com.porcupinestudios.lotrport.content.LotrItems;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import net.minecraft.client.model.HumanoidModel;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeDeformation;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.world.entity.EquipmentSlot;
import net.minecraft.world.entity.LivingEntity;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.ItemStack;
import net.neoforged.neoforge.client.extensions.common.IClientItemExtensions;
import net.neoforged.neoforge.client.extensions.common.RegisterClientExtensionsEvent;

/**
 * LOTR's special armor models (crested and winged helmets, robes, turbans, hats, the swan chestplate), generated by
 * {@code converter/armor_models.py} from LOTR's model classes into {@code lotr_port/content/armor_models.json}: one
 * HumanoidModel per model and inflation, handed to the armor layer through NeoForge's item extension. The armor
 * layer still picks the parts for the slot and copies the wearer's pose, and the texture is the piece's armor layer
 * texture (LOTR's textures already hold the extra boxes' UVs).
 */
public final class ArmorModels {
    private static final String[] PARTS = {"head", "hat", "body", "right_arm", "left_arm", "right_leg", "left_leg"};
    private static final Map<String, HumanoidModel<LivingEntity>> BAKED = new HashMap<>();

    private ArmorModels() {}

    static void register(RegisterClientExtensionsEvent event) {
        List<JsonObject> file = ContentData.read("armor_models.json");
        if (file.isEmpty()) {
            return;
        }
        JsonObject models = file.get(0).getAsJsonObject("models");
        for (Map.Entry<String, JsonElement> e : file.get(0).getAsJsonObject("items").entrySet()) {
            var holder = LotrItems.BY_ID.get(e.getKey());
            String key = e.getValue().getAsJsonObject().get("model").getAsString();
            if (holder == null || !models.has(key)) {
                continue;
            }
            JsonObject def = models.getAsJsonObject(key);
            Item item = holder.get();
            event.registerItem(new IClientItemExtensions() {
                @Override
                public HumanoidModel<?> getHumanoidArmorModel(LivingEntity entity, ItemStack stack, EquipmentSlot slot,
                        HumanoidModel<?> original) {
                    return BAKED.computeIfAbsent(key, k -> bake(def));
                }
            }, item);
        }
    }

    static HumanoidModel<LivingEntity> bake(JsonObject def) {
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
        JsonObject parts = def.getAsJsonObject("parts");
        for (String name : PARTS) {
            JsonObject part = parts.has(name) ? parts.getAsJsonObject(name) : new JsonObject();
            add(root, name, part);
        }
        JsonArray size = def.getAsJsonArray("texture");
        ModelPart baked = LayerDefinition.create(mesh, size.get(0).getAsInt(), size.get(1).getAsInt()).bakeRoot();
        return new HumanoidModel<>(baked);
    }

    private static void add(PartDefinition parent, String name, JsonObject part) {
        CubeListBuilder cubes = CubeListBuilder.create();
        if (part.has("cubes")) {
            for (JsonElement c : part.getAsJsonArray("cubes")) {
                JsonObject cube = c.getAsJsonObject();
                float[] o = floats(cube.getAsJsonArray("origin"));
                float[] s = floats(cube.getAsJsonArray("size"));
                float[] uv = floats(cube.getAsJsonArray("uv"));
                cubes.texOffs((int) uv[0], (int) uv[1]).mirror(cube.has("mirror") && cube.get("mirror").getAsBoolean())
                        .addBox(o[0], o[1], o[2], s[0], s[1], s[2],
                                new CubeDeformation(cube.has("inflate") ? cube.get("inflate").getAsFloat() : 0f));
            }
        }
        float[] p = part.has("pivot") ? floats(part.getAsJsonArray("pivot")) : new float[3];
        float[] r = part.has("rotation") ? floats(part.getAsJsonArray("rotation")) : new float[3];
        PartDefinition def = parent.addOrReplaceChild(name, cubes, PartPose.offsetAndRotation(p[0], p[1], p[2], r[0], r[1], r[2]));
        if (part.has("children")) {
            int n = 0;
            for (JsonElement child : part.getAsJsonArray("children")) {
                add(def, "child_" + n++, child.getAsJsonObject());
            }
        }
    }

    private static float[] floats(JsonArray a) {
        float[] out = new float[a.size()];
        for (int i = 0; i < out.length; i++) {
            out[i] = a.get(i).getAsFloat();
        }
        return out;
    }
}
