package com.porcupinestudios.lotrport.border;

import com.mojang.serialization.Codec;
import com.mojang.serialization.codecs.RecordCodecBuilder;
import com.porcupinestudios.lotrport.LotrPort;
import com.porcupinestudios.lotrport.npc.NpcSpawns;
import com.porcupinestudios.ringbearer.api.data.CodecJsonLoader;
import java.util.Map;
import java.util.Optional;
import net.minecraft.resources.ResourceLocation;
import net.neoforged.neoforge.common.NeoForge;
import net.neoforged.neoforge.event.AddReloadListenerEvent;

/**
 * Border data, all reloading with /reload: {@code borders/settings.json} ({@link Settings}), the original map's holders
 * {@code border_base/biomes.json} ({@link Base}, generated by {@code converter/borders.py}) and each faction's people
 * for land it takes, {@code border_spawns/<faction ns>/<faction path>.json} (the npc_spawns format).
 */
public final class BorderData {
    /**
     * @param claimRadius map pixels (128 blocks) a colony reaches from its Hall
     * @param peoplePerPixel one more pixel of reach per this many people (0: none)
     * @param maxRadius the most a colony reaches
     * @param recomputeTicks how often borders are worked out again (population changes); events also redo them
     * @param conqueredShare chance a spawn in taken land uses the holder's people instead of the biome's
     * @param enemyFactor weight factor for the biome's people who are the holder's enemies, in taken land
     * @param kingdomPledgeAlignment alignment with a player kingdom needed to pledge to it
     * @param rulerAlignment alignment a kingdom's founder starts with in it
     * @param kingdomNeedsColony a player must hold a colony to found a kingdom
     */
    public record Settings(double claimRadius, int peoplePerPixel, double maxRadius, int recomputeTicks,
            float conqueredShare, float enemyFactor, float kingdomPledgeAlignment, float rulerAlignment,
            boolean kingdomNeedsColony) {
        public static final Settings DEFAULT = new Settings(2, 10, 6, 1200, 0.75f, 0.25f, 50, 100, false);
        public static final Codec<Settings> CODEC = RecordCodecBuilder.create(i -> i.group(
                Codec.DOUBLE.optionalFieldOf("claim_radius", DEFAULT.claimRadius).forGetter(Settings::claimRadius),
                Codec.INT.optionalFieldOf("people_per_pixel", DEFAULT.peoplePerPixel).forGetter(Settings::peoplePerPixel),
                Codec.DOUBLE.optionalFieldOf("max_radius", DEFAULT.maxRadius).forGetter(Settings::maxRadius),
                Codec.INT.optionalFieldOf("recompute_ticks", DEFAULT.recomputeTicks).forGetter(Settings::recomputeTicks),
                Codec.FLOAT.optionalFieldOf("conquered_share", DEFAULT.conqueredShare).forGetter(Settings::conqueredShare),
                Codec.FLOAT.optionalFieldOf("enemy_factor", DEFAULT.enemyFactor).forGetter(Settings::enemyFactor),
                Codec.FLOAT.optionalFieldOf("kingdom_pledge_alignment", DEFAULT.kingdomPledgeAlignment)
                        .forGetter(Settings::kingdomPledgeAlignment),
                Codec.FLOAT.optionalFieldOf("ruler_alignment", DEFAULT.rulerAlignment).forGetter(Settings::rulerAlignment),
                Codec.BOOL.optionalFieldOf("kingdom_needs_colony", DEFAULT.kingdomNeedsColony)
                        .forGetter(Settings::kingdomNeedsColony))
                .apply(i, Settings::new));
    }

    /**
     * The original map: biome -> the faction holding it. Biomes not listed are nobody's (wilds, seas). {@code fill}:
     * water biomes (rivers, lakes) that take the holder of the land around them ({@link WaterFill}).
     */
    public record Base(Map<ResourceLocation, ResourceLocation> biomes, java.util.List<ResourceLocation> fill) {
        public static final Codec<Base> CODEC = RecordCodecBuilder.create(i -> i.group(
                Codec.unboundedMap(ResourceLocation.CODEC, ResourceLocation.CODEC).fieldOf("biomes")
                        .forGetter(Base::biomes),
                ResourceLocation.CODEC.listOf().optionalFieldOf("fill", java.util.List.of()).forGetter(Base::fill))
                .apply(i, Base::new));
    }

    private static final CodecJsonLoader<Settings> SETTINGS = new CodecJsonLoader<>("borders", Settings.CODEC);
    private static final CodecJsonLoader<Base> BASE = new CodecJsonLoader<>("border_base", Base.CODEC);
    private static final CodecJsonLoader<NpcSpawns.Table> SPAWNS =
            new CodecJsonLoader<>("border_spawns", NpcSpawns.Table.CODEC);
    private static Settings override;

    private BorderData() {}

    public static void register() {
        NeoForge.EVENT_BUS.addListener((AddReloadListenerEvent e) -> {
            e.addListener(SETTINGS);
            e.addListener(BASE);
            e.addListener(SPAWNS);
        });
    }

    public static Settings settings() {
        return override != null ? override : SETTINGS.entries().getOrDefault(LotrPort.id("settings"), Settings.DEFAULT);
    }

    /** Tests: use these settings until called with null. */
    public static void override(Settings settings) {
        override = settings;
    }

    /** Biome -> original holder, merged over every {@code border_base} file. */
    public static Map<ResourceLocation, ResourceLocation> base() {
        Map<ResourceLocation, ResourceLocation> all = new java.util.HashMap<>();
        BASE.entries().values().forEach(b -> all.putAll(b.biomes()));
        return all;
    }

    /** Water biomes that take the holder of the land around them, over every {@code border_base} file. */
    public static java.util.Set<ResourceLocation> fill() {
        java.util.Set<ResourceLocation> all = new java.util.HashSet<>();
        BASE.entries().values().forEach(b -> all.addAll(b.fill()));
        return all;
    }

    /** The people a faction sends into land it takes, if it has a list. */
    public static Optional<NpcSpawns.Table> spawns(ResourceLocation faction) {
        return Optional.ofNullable(SPAWNS.entries().get(ResourceLocation.fromNamespaceAndPath(LotrPort.MOD_ID,
                faction.getNamespace() + "/" + faction.getPath())));
    }

    /** A reload changes the base: Borders keys its cache on this. */
    static Object baseVersion() {
        return BASE.entries();
    }
}
