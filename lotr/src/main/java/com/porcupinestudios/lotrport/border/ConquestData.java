package com.porcupinestudios.lotrport.border;

import com.mojang.serialization.Codec;
import com.mojang.serialization.codecs.RecordCodecBuilder;
import com.porcupinestudios.lotrport.LotrPort;
import com.porcupinestudios.ringbearer.api.data.CodecJsonLoader;
import java.util.HashMap;
import java.util.Map;
import net.minecraft.resources.ResourceLocation;
import net.neoforged.neoforge.common.NeoForge;
import net.neoforged.neoforge.event.AddReloadListenerEvent;

/**
 * Conquest data, reloading with /reload: {@code conquest/settings.json} ({@link Settings}: pressure, decay, assaults
 * and their losses), {@code conquest_defence/*.json} ({@link Defence}: how hard each holder's land is to take) and
 * {@code conquest_terrain/*.json} ({@link Terrain}: biome -> defence factor, generated by {@code converter/borders.py}
 * from hilliness and mountain ranges).
 */
public final class ConquestData {
    /**
     * @param killPressure pressure one kill of the holder's people adds, times the victim faction's kill value
     * @param dayTicks length of a conquest day (decay, recovery, injuries)
     * @param pressureDecay share of pressure lost per day
     * @param damageRecovery share of assault damage the defence regains per day
     * @param flipMargin pressure must reach defence x this to take a square
     * @param claimTerrainCost colony claim strength (pixels) a square needs per terrain factor above 1, so colonies
     *     claim mountains only when big and near
     * @param soldierAttack defence an assaulting soldier strikes off
     * @param assaultPressure pressure each assaulting soldier adds
     * @param deathBase chance an assaulting soldier dies
     * @param deathPerDefence extra death chance per point of defence per soldier sent
     * @param deathMax most a soldier's death chance can be
     * @param injuryChance chance a surviving soldier comes back injured
     * @param injuryDays days an injured soldier can't fight
     * @param raceLossCount this many of one race dying in one assault gives that race's citizens {@code raceThought}
     * @param heavyLossShare this share of those sent dying (and at least {@code heavyLossMin}) gives the whole colony
     *     {@code heavyThought}
     */
    public record Settings(float killPressure, int dayTicks, float pressureDecay, float damageRecovery, float flipMargin,
            double claimTerrainCost, float soldierAttack, float assaultPressure, float deathBase,
            float deathPerDefence, float deathMax, float injuryChance, int injuryDays, int raceLossCount,
            float heavyLossShare, int heavyLossMin) {
        public static final Settings DEFAULT = new Settings(1f, 24000, 0.1f, 0.25f, 1f, 1.0, 2f, 1f, 0.05f, 0.02f,
                0.6f, 0.3f, 3, 3, 0.4f, 5);
        public static final Codec<Settings> CODEC = RecordCodecBuilder.create(i -> i.group(
                Codec.FLOAT.optionalFieldOf("kill_pressure", DEFAULT.killPressure).forGetter(Settings::killPressure),
                Codec.INT.optionalFieldOf("day_ticks", DEFAULT.dayTicks).forGetter(Settings::dayTicks),
                Codec.FLOAT.optionalFieldOf("pressure_decay", DEFAULT.pressureDecay).forGetter(Settings::pressureDecay),
                Codec.FLOAT.optionalFieldOf("damage_recovery", DEFAULT.damageRecovery)
                        .forGetter(Settings::damageRecovery),
                Codec.FLOAT.optionalFieldOf("flip_margin", DEFAULT.flipMargin).forGetter(Settings::flipMargin),
                Codec.DOUBLE.optionalFieldOf("claim_terrain_cost", DEFAULT.claimTerrainCost)
                        .forGetter(Settings::claimTerrainCost),
                Codec.FLOAT.optionalFieldOf("soldier_attack", DEFAULT.soldierAttack).forGetter(Settings::soldierAttack),
                Codec.FLOAT.optionalFieldOf("assault_pressure", DEFAULT.assaultPressure)
                        .forGetter(Settings::assaultPressure),
                Codec.FLOAT.optionalFieldOf("death_base", DEFAULT.deathBase).forGetter(Settings::deathBase),
                Codec.FLOAT.optionalFieldOf("death_per_defence", DEFAULT.deathPerDefence)
                        .forGetter(Settings::deathPerDefence),
                Codec.FLOAT.optionalFieldOf("death_max", DEFAULT.deathMax).forGetter(Settings::deathMax),
                Codec.FLOAT.optionalFieldOf("injury_chance", DEFAULT.injuryChance).forGetter(Settings::injuryChance),
                Codec.INT.optionalFieldOf("injury_days", DEFAULT.injuryDays).forGetter(Settings::injuryDays),
                Codec.INT.optionalFieldOf("race_loss_count", DEFAULT.raceLossCount).forGetter(Settings::raceLossCount),
                Codec.FLOAT.optionalFieldOf("heavy_loss_share", DEFAULT.heavyLossShare)
                        .forGetter(Settings::heavyLossShare),
                Codec.INT.optionalFieldOf("heavy_loss_min", DEFAULT.heavyLossMin).forGetter(Settings::heavyLossMin))
                .apply(i, Settings::new));
    }

    /**
     * How hard land is to take before terrain: {@code factions} per holder, {@code default} for any other great power,
     * {@code kingdom} for a kingdom's land, plus per colony of the holder in reach: {@code per_soldier} and
     * {@code per_citizen} (a built-up colony defends its land).
     */
    public record Defence(float defaultDefence, float kingdom, Map<ResourceLocation, Float> factions, float perSoldier,
            float perCitizen) {
        public static final Defence DEFAULT = new Defence(20, 10, Map.of(), 2, 0.25f);
        public static final Codec<Defence> CODEC = RecordCodecBuilder.create(i -> i.group(
                Codec.FLOAT.optionalFieldOf("default", DEFAULT.defaultDefence).forGetter(Defence::defaultDefence),
                Codec.FLOAT.optionalFieldOf("kingdom", DEFAULT.kingdom).forGetter(Defence::kingdom),
                Codec.unboundedMap(ResourceLocation.CODEC, Codec.FLOAT).optionalFieldOf("factions", Map.of())
                        .forGetter(Defence::factions),
                Codec.FLOAT.optionalFieldOf("per_soldier", DEFAULT.perSoldier).forGetter(Defence::perSoldier),
                Codec.FLOAT.optionalFieldOf("per_citizen", DEFAULT.perCitizen).forGetter(Defence::perCitizen))
                .apply(i, Defence::new));
    }

    /** Biome -> defence factor (1 = flat open land). */
    public record Terrain(Map<ResourceLocation, Double> biomes) {
        public static final Codec<Terrain> CODEC = RecordCodecBuilder.create(i -> i.group(
                Codec.unboundedMap(ResourceLocation.CODEC, Codec.DOUBLE).fieldOf("biomes").forGetter(Terrain::biomes))
                .apply(i, Terrain::new));
    }

    private static final CodecJsonLoader<Settings> SETTINGS = new CodecJsonLoader<>("conquest", Settings.CODEC);
    private static final CodecJsonLoader<Defence> DEFENCE = new CodecJsonLoader<>("conquest_defence", Defence.CODEC);
    private static final CodecJsonLoader<Terrain> TERRAIN = new CodecJsonLoader<>("conquest_terrain", Terrain.CODEC);
    private static Settings override;

    private ConquestData() {}

    public static void register() {
        NeoForge.EVENT_BUS.addListener((AddReloadListenerEvent e) -> {
            e.addListener(SETTINGS);
            e.addListener(DEFENCE);
            e.addListener(TERRAIN);
        });
    }

    public static Settings settings() {
        return override != null ? override : SETTINGS.entries().getOrDefault(LotrPort.id("settings"), Settings.DEFAULT);
    }

    /** Tests: use these settings until called with null. */
    public static void override(Settings settings) {
        override = settings;
    }

    public static Defence defence() {
        return DEFENCE.entries().getOrDefault(LotrPort.id("defence"), Defence.DEFAULT);
    }

    /** Biome -> factor, merged over the files. */
    public static Map<ResourceLocation, Double> terrain() {
        Map<ResourceLocation, Double> all = new HashMap<>();
        TERRAIN.entries().values().forEach(t -> all.putAll(t.biomes()));
        return all;
    }

    static Object terrainVersion() {
        return TERRAIN.entries();
    }
}
