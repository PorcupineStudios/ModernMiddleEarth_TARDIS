"""Writes the slope blocks' assets and data (run from harness/: python3 tools/slopes.py): for each material and profile,
OBJ models right side up and upside down (true wedge geometry, faces wound outward), the block-model JSONs (NeoForge's
OBJ loader), blockstates (facing turns it, half picks the model), item models, loot tables and recipes. Profiles match
SlopeBlock.Profile: the 45-degree slope (0 -> 1) and the gentle pair's halves (0 -> 1/2, 1/2 -> 1)."""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "src/main/resources"
A, D = ROOT / "assets/ringbearer_harness", ROOT / "data/ringbearer_harness"
MATERIALS = {"oak": ("minecraft:block/oak_planks", "minecraft:oak_planks"),
             "stone": ("minecraft:block/smooth_stone", "minecraft:smooth_stone")}
PROFILES = {"slope": (0.0, 1.0), "slope_low": (0.0, 0.5), "slope_high": (0.5, 1.0)}


def solid(h0, h1, top):
    """The prism's faces (lists of corner points) for a block facing north: u runs from the south edge (z 1) to the
    north edge (z 0); the face rises from h0 to h1 along it."""
    def p(x, u, y):
        return (x, 1 - y if top else y, 1 - u)
    prof = [(0, 0), (1, 0), (1, h1)] + ([(0, h0)] if h0 > 0 else [])
    sides = [[p(x, u, y) for u, y in prof] for x in (0, 1)]
    faces = sides[:]
    n = len(prof)
    for i in range(n):  # the faces round the profile's edges
        (u0, y0), (u1, y1) = prof[i], prof[(i + 1) % n]
        faces.append([p(0, u0, y0), p(1, u0, y0), p(1, u1, y1), p(0, u1, y1)])
    return faces


def wound(face, centre):
    """Corners ordered counter-clockwise seen from outside, its outward normal, and UVs."""
    c = [sum(v[i] for v in face) / len(face) for i in range(3)]
    a, b = [face[1][i] - face[0][i] for i in range(3)], [face[2][i] - face[0][i] for i in range(3)]
    n = [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]]
    if sum(n[i] * (c[i] - centre[i]) for i in range(3)) < 0:
        face, n = face[::-1], [-x for x in n]
    length = math.sqrt(sum(x * x for x in n))
    n = [x / length for x in n]
    k = max(range(3), key=lambda i: abs(n[i]))
    axes = [i for i in range(3) if i != k]
    uv = [(v[axes[0]], v[axes[1]]) for v in face]
    return face, n, uv


def obj(h0, h1, top):
    faces = solid(h0, h1, top)
    corners = {v for f in faces for v in f}
    centre = [sum(v[i] for v in corners) / len(corners) for i in range(3)]
    lines = ["# generated by harness/tools/slopes.py", "mtllib slope.mtl", "usemtl slope"]
    vs, vts, vns, fs = [], [], [], []
    for f in faces:
        f, n, uv = wound(f, centre)
        if len(set(f)) < 3:
            continue
        vns.append(n)
        idx = []
        for v, t in zip(f, uv):
            vs.append(v)
            vts.append(t)
            idx.append(f"{len(vs)}/{len(vts)}/{len(vns)}")
        fs.append("f " + " ".join(idx))
    lines += [f"v {v[0]:g} {v[1]:g} {v[2]:g}" for v in vs]
    lines += [f"vt {t[0]:g} {t[1]:g}" for t in vts]
    lines += [f"vn {n[0]:.4f} {n[1]:.4f} {n[2]:.4f}" for n in vns]
    return "\n".join(lines + fs) + "\n"


def write(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(data if isinstance(data, str) else json.dumps(data, indent=2) + "\n")


(A / "models/block/slope.mtl").write_text("newmtl slope\nmap_Kd #texture\n")
for shape, (h0, h1) in PROFILES.items():
    for half in ("bottom", "top"):
        write(A / f"models/block/{shape}_{half}.obj", obj(h0, h1, half == "top"))
for mat, (texture, item) in MATERIALS.items():
    for shape in PROFILES:
        name = f"{mat}_{shape}"
        for half in ("bottom", "top"):
            write(A / f"models/block/{name}_{half}.json", {
                "loader": "neoforge:obj", "model": f"ringbearer_harness:models/block/{shape}_{half}.obj",
                "flip_v": True, "textures": {"texture": texture, "particle": texture}})
        variants = {}
        for facing, y in (("north", 0), ("east", 90), ("south", 180), ("west", 270)):
            for half in ("bottom", "top"):
                v = {"model": f"ringbearer_harness:block/{name}_{half}"}
                if y:
                    v["y"] = y
                variants[f"facing={facing},half={half}"] = v
        write(A / f"blockstates/{name}.json", {"variants": variants})
        write(A / f"models/item/{name}.json", {"parent": f"ringbearer_harness:block/{name}_bottom", "display": {
            "gui": {"rotation": [30, 225, 0], "translation": [0, 0, 0], "scale": [0.625, 0.625, 0.625]},
            "ground": {"rotation": [0, 0, 0], "translation": [0, 3, 0], "scale": [0.25, 0.25, 0.25]},
            "fixed": {"rotation": [0, 0, 0], "translation": [0, 0, 0], "scale": [0.5, 0.5, 0.5]},
            "thirdperson_righthand": {"rotation": [75, 45, 0], "translation": [0, 2.5, 0],
                                      "scale": [0.375, 0.375, 0.375]},
            "firstperson_righthand": {"rotation": [0, 45, 0], "translation": [0, 0, 0], "scale": [0.4, 0.4, 0.4]}}})
        write(D / f"loot_table/blocks/{name}.json", {"type": "minecraft:block", "pools": [{"rolls": 1, "entries": [
            {"type": "minecraft:item", "name": f"ringbearer_harness:{name}"}],
            "conditions": [{"condition": "minecraft:survives_explosion"}]}]})
    # the 45-degree slope like stairs; the gentle halves: low from a row (like slabs), high stacked on it
    write(D / f"recipe/{mat}_slope.json", {"type": "minecraft:crafting_shaped", "category": "building",
        "pattern": ["#  ", "## ", "###"], "key": {"#": {"item": item}},
        "result": {"id": f"ringbearer_harness:{mat}_slope", "count": 6}})
    write(D / f"recipe/{mat}_slope_low.json", {"type": "minecraft:crafting_shaped", "category": "building",
        "pattern": ["  #", "###"], "key": {"#": {"item": item}},
        "result": {"id": f"ringbearer_harness:{mat}_slope_low", "count": 6}})
    write(D / f"recipe/{mat}_slope_high.json", {"type": "minecraft:crafting_shaped", "category": "building",
        "pattern": [" ##", "###"], "key": {"#": {"item": item}},
        "result": {"id": f"ringbearer_harness:{mat}_slope_high", "count": 4}})
print("slopes written")
